package main

import (
	"fmt"
	"os"
)

const version = "0.1.0"

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	switch os.Args[1] {
	case "version":
		fmt.Println(version)
	default:
		usage()
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: herdr-remoted serve | pair [status|allow|deny|cancel] [--json] | devices ls [--json] | devices rm <id> | version")
	os.Exit(2)
}
